-- Baseline schema for ONE mail domain.
-- Every domain instance has its own database; no table references another domain.
-- Remote parties are stored as plain addresses, never as foreign keys.
-- SQL is kept portable between PostgreSQL (primary) and H2 in PostgreSQL mode (local/test).

CREATE TABLE organizations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128)             NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_organizations_name UNIQUE (name)
);

CREATE TABLE users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  BIGINT                   NOT NULL,
    username         VARCHAR(64)              NOT NULL, -- lowercase local part of the address
    display_name     VARCHAR(128)             NOT NULL,
    password_hash    VARCHAR(255)             NOT NULL, -- encoded hash only, never plaintext
    role             VARCHAR(16)              NOT NULL,
    status           VARCHAR(16)              NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT fk_users_organization FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'MEMBER')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- One row per logical message known to this domain (authored here or received from a peer).
CREATE TABLE mail_messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id      VARCHAR(255)             NOT NULL, -- globally stable id: <uuid>@<origin-domain>
    sender_address  VARCHAR(320)             NOT NULL,
    sender_user_id  BIGINT,                            -- set only when the sender is a local user
    subject         VARCHAR(998)             NOT NULL,
    body_text       VARCHAR(100000)          NOT NULL, -- plain text; rendered escaped by clients
    origin          VARCHAR(16)              NOT NULL,
    status          VARCHAR(16)              NOT NULL,
    in_reply_to     VARCHAR(255),
    sent_at         TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uk_mail_messages_message_id UNIQUE (message_id),
    CONSTRAINT fk_mail_messages_sender FOREIGN KEY (sender_user_id) REFERENCES users (id),
    CONSTRAINT ck_mail_messages_origin CHECK (origin IN ('LOCAL', 'REMOTE')),
    CONSTRAINT ck_mail_messages_status CHECK (status IN ('DRAFT', 'SENT', 'RECALLED'))
);

-- Recipients of a message and the per-recipient delivery state (tracked by the sender's domain).
CREATE TABLE mail_recipients (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail_message_id  BIGINT                   NOT NULL,
    address          VARCHAR(320)             NOT NULL,
    recipient_type   VARCHAR(8)               NOT NULL,
    delivery_status  VARCHAR(24)              NOT NULL,
    last_error       VARCHAR(512),
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_mail_recipients_message_address UNIQUE (mail_message_id, address),
    CONSTRAINT fk_mail_recipients_message FOREIGN KEY (mail_message_id) REFERENCES mail_messages (id) ON DELETE CASCADE,
    CONSTRAINT ck_mail_recipients_type CHECK (recipient_type IN ('TO', 'CC', 'BCC')),
    CONSTRAINT ck_mail_recipients_status CHECK (delivery_status IN
        ('PENDING', 'DELIVERED', 'RETRYING', 'FAILED', 'RECALLED', 'RECALL_FAILED'))
);

-- A local user's view of a message (folder, flags). Ownership checks are enforced on this table.
CREATE TABLE mailbox_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id    BIGINT                   NOT NULL,
    mail_message_id  BIGINT                   NOT NULL,
    folder           VARCHAR(16)              NOT NULL,
    is_read          BOOLEAN                  NOT NULL DEFAULT FALSE,
    is_starred       BOOLEAN                  NOT NULL DEFAULT FALSE,
    recalled         BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uk_mailbox_items_owner_message_folder UNIQUE (owner_user_id, mail_message_id, folder),
    CONSTRAINT fk_mailbox_items_owner FOREIGN KEY (owner_user_id) REFERENCES users (id),
    CONSTRAINT fk_mailbox_items_message FOREIGN KEY (mail_message_id) REFERENCES mail_messages (id) ON DELETE CASCADE,
    CONSTRAINT ck_mailbox_items_folder CHECK (folder IN ('INBOX', 'SENT', 'DRAFTS', 'TRASH'))
);

CREATE INDEX idx_mailbox_items_owner_folder ON mailbox_items (owner_user_id, folder, created_at);
CREATE INDEX idx_mail_recipients_status ON mail_recipients (delivery_status);

-- Append-only security audit trail. Never store passwords, tokens or mail bodies here.
CREATE TABLE security_audit_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type        VARCHAR(64)              NOT NULL,
    outcome           VARCHAR(16)              NOT NULL,
    actor_user_id     BIGINT,
    actor_identifier  VARCHAR(320),             -- username or peer domain
    source_ip         VARCHAR(64),
    target_type       VARCHAR(64),
    target_id         VARCHAR(255),
    detail            VARCHAR(1024),
    occurred_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_security_audit_events_outcome CHECK (outcome IN ('SUCCESS', 'FAILURE', 'DENIED'))
);

CREATE INDEX idx_security_audit_events_occurred_at ON security_audit_events (occurred_at);
CREATE INDEX idx_security_audit_events_type ON security_audit_events (event_type, occurred_at);
