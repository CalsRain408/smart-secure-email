-- Phase 3: cross-domain delivery.

-- Recipient rows of messages received from a peer are display-only.
ALTER TABLE mail_recipients DROP CONSTRAINT ck_mail_recipients_status;
ALTER TABLE mail_recipients ADD CONSTRAINT ck_mail_recipients_status CHECK (delivery_status IN
    ('PENDING', 'DELIVERED', 'RETRYING', 'FAILED', 'RECALLED', 'RECALL_FAILED', 'NOT_TRACKED'));

-- Transactional outbox: one row per (message, peer domain), written in the send transaction.
-- The recipients to deliver are the message's recipients of that domain still PENDING/RETRYING.
CREATE TABLE delivery_outbox (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail_message_id  BIGINT                   NOT NULL,
    peer_domain      VARCHAR(253)             NOT NULL,
    status           VARCHAR(16)              NOT NULL,
    attempts         INTEGER                  NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error       VARCHAR(512),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uk_delivery_outbox_message_peer UNIQUE (mail_message_id, peer_domain),
    CONSTRAINT fk_delivery_outbox_message FOREIGN KEY (mail_message_id) REFERENCES mail_messages (id) ON DELETE CASCADE,
    CONSTRAINT ck_delivery_outbox_status CHECK (status IN ('PENDING', 'DONE', 'FAILED'))
);

CREATE INDEX idx_delivery_outbox_due ON delivery_outbox (status, next_attempt_at);

-- Replay protection for inbound federation requests: a nonce is accepted once per origin.
CREATE TABLE federation_nonces (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_domain  VARCHAR(253)             NOT NULL,
    nonce          VARCHAR(64)              NOT NULL,
    expires_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_federation_nonces_origin_nonce UNIQUE (origin_domain, nonce)
);

CREATE INDEX idx_federation_nonces_expires_at ON federation_nonces (expires_at);
